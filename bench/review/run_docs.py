SPEC_MD = """# 仕様書: チームのメモ（notes）
## 目的
組織ごとにメモを共有する Python のライブラリ（notes パッケージ）を作る。SQLite に保存する。

## 機能要件
- R1 メモを作成できる
  - 題名は1〜100文字で、空白だけは不可。本文は10000文字まで。タグは5個まで（重複も数える。保存は重複を除く）、各タグは英小文字・数字・ハイフンの1〜20文字。tags はタグの列（文字列そのものは不可）
  - メモ・タグ・監査ログの記録は、1つのトランザクションで行う（途中で失敗したら何も残さない）
- R2 メモを閲覧できる
  - 見られるのは同じ組織の利用者だけ。非公開のメモは作成者だけ
  - 見られないメモ（他の組織・他人の非公開・存在しない）は、どれも NotFound にする（存在を明かさない）
  - 閲覧のたびに閲覧数を1増やす。同時に閲覧されても数え漏れがないこと
- R3 一覧・検索ができる
  - 対象は自分の組織のメモで、他人の非公開メモは含めない
  - 一覧: page は1以上、per_page は1〜50、sort は updated（新しい順）か title（題名順）だけ。範囲外は ValidationError
  - 検索: 検索語は1〜100文字で、空白だけは不可。% と _ も普通の文字として部分一致で探す。タグでの絞り込みは、指定したタグのどれかを持つメモ（OR）。タグも R1 の規則で検査する
  - SQL は必ずプレースホルダーで値を渡す（利用者の入力を SQL の文字列に埋め込まない）
- R4 メモを更新・削除できる
  - できるのは作成者と、同じ組織の管理者だけ（それ以外は Forbidden）。ただし非公開のメモは作成者だけが扱える（管理者にも見えないので NotFound。R2 のとおり）
  - 更新は楽観的ロック: 呼び出し側が渡した version が最新でなければ Conflict。読み出しから書き込みの間に他の更新が入った場合も Conflict（後から書いた側が先の更新を消さない）
  - 更新でも R1 の入力検証を行う（タグを含む）
  - 削除はタグとメモを1つのトランザクションで消す。失敗したら例外を呼び出し側に伝える（握りつぶさない）
- R5 管理者は、ある利用者のメモをすべて別の利用者に移せる
  - 管理者だけ。移す元・移す先・管理者がすべて同じ組織のときだけ（それ以外は Forbidden）
  - 全部移すか、何も移さないか（途中で失敗したら元のまま）
- R6 管理者は組織の監査ログを出力できる
  - 利用者の api_key は末尾4文字以外を * で伏せる。8文字未満の鍵はすべて伏せる
- R7 利用者ごとの書き込み回数の制限（RateLimiter）
  - window 秒の枠の中で limit 回まで。超えたら RateLimited
  - 枠の開始からちょうど window 秒たったら新しい枠になる
  - 複数のスレッドから同時に呼ばれても、上限を超えて許さない
- R8 メモの共有リンク（署名付き・期限付き）
  - リンクの形は「note_id.期限.署名」（note_id と期限は10進の数字だけ、署名は16進の小文字64文字）。HMAC-SHA256 の署名。期限の時刻ちょうど以降は無効
  - 期限切れ・改ざん・形の崩れたリンクは、どれも Forbidden

## 非機能要件
- R9 ログ・例外のメッセージ・出力に、メモの本文・共有リンクの署名・api_key を出さない
- R10 例外が起きたらトランザクションをロールバックし、接続を次の操作に使える状態に戻す

## 受け入れ条件
- AC1 R1 の規則どおりに作成・拒否され、失敗時に何も残らない
- AC2 R2 の規則どおりに見え方が決まり、閲覧数が正確に増える
- AC3 R3 の規則どおりに一覧・検索の結果と入力の拒否が決まる
- AC4 R4 の規則どおりに更新・削除・競合・拒否が決まる
- AC5 R5 の規則どおりに移管・拒否され、失敗時に元のまま
- AC6 監査ログの api_key が伏せられている
- AC7 R7 の規則どおりに制限される（枠の境界・同時の呼び出しを含む）
- AC8 R8 の規則どおりにリンクが検証される（期限の境界を含む）
- AC9 ログ・出力に機密情報が出ない
- AC10 例外の後も接続を使い続けられる

## リスク
- K1 他の組織・他人の非公開メモの漏えい（R2・R3・R4・R5）
- K2 SQL インジェクション（R3）
- K3 同時の更新・閲覧・呼び出しで、更新や数が失われる（R2・R4・R7）
- K4 途中の失敗による不整合（R1・R4・R5・R10）
- K5 機密情報の露出（R6・R9）
- K6 移管で組織の外にメモが渡る・一部だけ移る（R5）
- K7 監査ログから api_key が漏れる（R6）
- K8 期限切れ・改ざん・形の崩れた共有リンクを通す（R8）

## 不明点・矛盾点
- なし

## 対象外
- HTTP の API・認証（利用者の dict は、呼び出し側が確かめてから渡す。このライブラリは role・org_id を信用する）
- 接続の共有: 接続（db.connect）はスレッドごとに1つ使う。1つの接続を複数のスレッドで共有しない（「同時」は、別々の接続・別々のスレッドからの操作のこと）
"""

